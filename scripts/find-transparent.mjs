/**
 * Finds the images under public/ that are genuine cut-outs — a subject on a
 * transparent background — and writes the list to src/lib/transparent-images.ts.
 *
 * Having an alpha channel is not enough. A marketing banner saved as a PNG with
 * rounded corners has an alpha channel too, but it is a solid rectangle: shown
 * with `object-contain` on the page it reads as a pasted-on box. So this decodes
 * each image and asks two questions:
 *
 *   1. Are all four corners transparent?     (a rectangle fails this)
 *   2. Is a decent share of the whole image transparent?
 *
 * It also records whether the subject runs off the bottom of its own frame.
 * Cut-outs cropped at the torso need their hard bottom edge dissolved into the
 * hero behind them; ones that end cleanly inside the frame — a whole standing
 * figure, say — must not be faded, or the fade eats their feet.
 *
 * Only images that pass both are treated as cut-outs by SectionImage.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const DIRS = [
  "public/assets/images",
  "public/assets/images/slider",
  "public/assets/images/galery",
  "public/assets/images/brand",
  "public/images",
];

/** A pixel counts as transparent below this alpha value (0-255). */
const ALPHA_FLOOR = 16;

/** A subject covering this much of the bottom row is running off the edge. */
const BLEED_MIN = 0.06;

/** At least this share of the image must be transparent to count as a cut-out. */
const MIN_TRANSPARENT = 0.12;

async function inspect(file) {
  const image = sharp(file).ensureAlpha();
  const { width, height } = await image.metadata();
  if (!width || !height) return null;

  // Work from a small copy — we only need proportions, not detail.
  const size = 96;
  const { data } = await image
    .resize(size, size, { fit: "fill" })
    .raw()
    .toBuffer({ resolveWithObject: true });

  const alphaAt = (x, y) => data[(y * size + x) * 4 + 3];

  const corners = [
    alphaAt(0, 0),
    alphaAt(size - 1, 0),
    alphaAt(0, size - 1),
    alphaAt(size - 1, size - 1),
  ];

  if (corners.some((a) => a >= ALPHA_FLOOR)) return null;

  let clear = 0;
  for (let i = 3; i < data.length; i += 4) if (data[i] < ALPHA_FLOOR) clear += 1;

  const share = clear / (size * size);
  if (share < MIN_TRANSPARENT) return null;

  // How much of the bottom of the frame is still subject. A figure standing
  // inside its frame leaves this empty; one cropped at the waist fills it.
  //
  // Measured across the last few rows rather than the very last one: several of
  // these files are cropped hard but carry a row of transparent padding
  // underneath, and testing a single row calls those clean when they are not.
  let bottom = 0;
  for (let y = size - 2; y < size; y++) {
    let row = 0;
    for (let x = 0; x < size; x++) if (alphaAt(x, y) >= ALPHA_FLOOR) row += 1;
    bottom = Math.max(bottom, row);
  }

  return { share, bleeds: bottom / size >= BLEED_MIN };
}

const found = [];
const rejected = [];

for (const dir of DIRS) {
  if (!fs.existsSync(dir)) continue;

  for (const name of fs.readdirSync(dir)) {
    if (!/\.png$/i.test(name)) continue;

    const file = path.join(dir, name);
    if (fs.statSync(file).size < 6000) continue; // sprites and decorations

    const url = "/" + path.relative("public", file).split(path.sep).join("/");

    try {
      const result = await inspect(file);
      if (result) found.push({ url, ...result });
      else rejected.push(url);
    } catch {
      rejected.push(url);
    }
  }
}

found.sort((a, b) => a.url.localeCompare(b.url));

const module = `// GENERATED by scripts/find-transparent.mjs — do not edit by hand.
//
// Genuine cut-outs: a subject on a transparent background, verified by decoding
// the image rather than by trusting the file extension. SectionImage shows these
// whole, on no background; everything else is treated as a photograph and
// cropped with a soft edge fade.

const transparent = new Set<string>([
${found.map((f) => `  ${JSON.stringify(f.url)},`).join("\n")}
]);

// Cut-outs whose subject runs off the bottom of the file. Only these want the
// bottom edge dissolved into the section behind them — see .cutout-fade.
const bleedsBottom = new Set<string>([
${found.filter((f) => f.bleeds).map((f) => `  ${JSON.stringify(f.url)},`).join("\n")}
]);

/** True when the image is a cut-out that should sit directly on the page. */
export function isTransparent(src: string) {
  return transparent.has(src);
}

/**
 * True when the subject is cropped by the bottom of its own frame, so the hard
 * edge needs fading out. False for a cut-out that ends cleanly inside the frame:
 * fading one of those removes part of the subject.
 */
export function bleedsOffBottom(src: string) {
  return bleedsBottom.has(src);
}
`;

fs.writeFileSync("src/lib/transparent-images.ts", module);

console.log(`cut-outs: ${found.length}   (rejected as opaque or boxed: ${rejected.length})`);
console.log("wrote src/lib/transparent-images.ts\n");
console.log(`  of those, ${found.filter((f) => f.bleeds).length} run off the bottom edge
`);
for (const f of found.slice(0, 20)) {
  console.log(`  ${Math.round(f.share * 100).toString().padStart(3)}% clear  ${f.bleeds ? "bleeds" : "      "}  ${f.url}`);
}
